#!/usr/bin/env python3
"""
Bailian Teacher Proxy for SLIME OPD
===================================
模拟 SGLang 的 /generate 接口，内部调用阿里百炼 API 获取 teacher log-probs。

用法:
    python bailian_teacher_proxy.py --port 13141 --model qwen-max --api-key sk-xxx

SLIME 配置:
    --rm-url http://127.0.0.1:13141/generate
"""

import argparse
import asyncio
import json
import logging
import os
import sys
from typing import Optional

import aiohttp
from fastapi import FastAPI
from pydantic import BaseModel
import uvicorn

logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
logger = logging.getLogger(__name__)

app = FastAPI()

# Global state
TOKENIZER = None
API_KEY = None
API_BASE = "https://dashscope.aliyuncs.com/compatible-mode/v1"
MODEL_NAME = "qwen-max"


class GenerateRequest(BaseModel):
    input_ids: list[int] = []
    text: Optional[str] = None
    sampling_params: dict = {}
    return_logprob: bool = False
    logprob_start_len: int = 0


@app.on_event("startup")
async def startup():
    global TOKENIZER
    from transformers import AutoTokenizer

    tokenizer_path = app.state.tokenizer_path
    logger.info(f"Loading tokenizer from {tokenizer_path}...")
    TOKENIZER = AutoTokenizer.from_pretrained(tokenizer_path, trust_remote_code=True)
    logger.info(f"Tokenizer loaded. Vocab size: {TOKENIZER.vocab_size}")


@app.post("/generate")
async def generate(req: GenerateRequest):
    """SGLang-compatible /generate endpoint."""
    if not req.return_logprob:
        return {"meta_info": {}}

    # Decode input_ids to text
    if req.input_ids:
        text = TOKENIZER.decode(req.input_ids, skip_special_tokens=False)
    elif req.text:
        text = req.text
    else:
        return {"error": "No input_ids or text provided"}

    # Call Bailian Completions API with echo=True
    payload = {
        "model": MODEL_NAME,
        "prompt": text,
        "max_tokens": 1,
        "echo": True,
        "logprobs": 1,
        "temperature": 0,
    }

    headers = {
        "Authorization": f"Bearer {API_KEY}",
        "Content-Type": "application/json",
    }

    try:
        async with aiohttp.ClientSession() as session:
            async with session.post(
                f"{API_BASE}/completions", json=payload, headers=headers, timeout=aiohttp.ClientTimeout(total=60)
            ) as resp:
                if resp.status != 200:
                    error_text = await resp.text()
                    logger.error(f"Bailian API error {resp.status}: {error_text}")
                    return {"error": f"Bailian API error {resp.status}"}
                result = await resp.json()
    except Exception as e:
        logger.error(f"Bailian API call failed: {e}")
        return {"error": str(e)}

    # Convert OpenAI format → SGLang format
    try:
        logprobs_data = result["choices"][0]["logprobs"]
        token_logprobs = logprobs_data.get("token_logprobs", [])
        tokens = logprobs_data.get("tokens", [])

        # Build input_token_logprobs: [[log_prob, token_id], ...]
        # Exclude last token (generated by max_tokens=1)
        input_token_logprobs = []
        for i in range(min(len(tokens) - 1, len(req.input_ids))):
            logprob = token_logprobs[i] if i < len(token_logprobs) else 0.0
            if logprob is None:
                logprob = 0.0
            # Use original input_ids for token_id (same tokenizer assumption)
            input_token_logprobs.append([logprob, req.input_ids[i]])

        return {"meta_info": {"input_token_logprobs": input_token_logprobs}}
    except (KeyError, IndexError) as e:
        logger.error(f"Failed to parse Bailian response: {e}")
        logger.error(f"Response: {json.dumps(result, indent=2)[:500]}")
        return {"error": f"Parse error: {e}"}


@app.get("/health_generate")
async def health():
    return {"status": "ok"}


@app.get("/get_model_info")
async def model_info():
    return {"model_path": MODEL_NAME}


def main():
    global API_KEY, MODEL_NAME

    parser = argparse.ArgumentParser(description="Bailian Teacher Proxy for SLIME OPD")
    parser.add_argument("--port", type=int, default=13141)
    parser.add_argument("--model", type=str, default="qwen-max", help="Bailian model name")
    parser.add_argument("--api-key", type=str, default=None, help="Bailian API key (or set BAILIAN_API_KEY env)")
    parser.add_argument("--tokenizer-path", type=str, required=True, help="Path to Qwen tokenizer")
    args = parser.parse_args()

    API_KEY = args.api_key or os.environ.get("BAILIAN_API_KEY", "")
    MODEL_NAME = args.model
    app.state.tokenizer_path = args.tokenizer_path

    if not API_KEY:
        logger.warning("No API key provided! Set --api-key or BAILIAN_API_KEY env var")

    logger.info(f"Starting Bailian teacher proxy on port {args.port}")
    logger.info(f"Teacher model: {MODEL_NAME}")
    logger.info(f"Tokenizer: {args.tokenizer_path}")

    uvicorn.run(app, host="0.0.0.0", port=args.port, log_level="info")


if __name__ == "__main__":
    main()
